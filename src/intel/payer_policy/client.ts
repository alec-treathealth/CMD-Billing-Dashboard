/**
 * Messages API call for one payer key. One payer per invocation.
 *
 * Everything here is load-bearing for correctness rather than style, and each
 * piece was established by a live probe rather than from the docs alone:
 *
 *  - THREE stop reasons, not two. `end_turn`, `pause_turn` (resend unchanged),
 *    and `tool_use`. Because `emit_findings` is a client tool and web_search is a
 *    server tool, the API returns `tool_use` and defers the search when both land
 *    in one parallel group, so every healthy run is multi-turn. Treating any of
 *    the three as terminal is a silent-truncation bug.
 *  - Assistant content is echoed back BYTE-IDENTICAL: the same parsed array, never
 *    filtered or rebuilt. Thinking blocks (Opus 5 emits them unrequested),
 *    server_tool_use blocks, and web_search results with their `encrypted_content`
 *    must round-trip exactly or the resend 400s.
 *  - `container` is REQUIRED to continue. Dynamic filtering runs web_search inside
 *    an auto-provisioned code-execution container; without reattaching, turn 2
 *    returns 400 "container_id is required when there are pending tool uses
 *    generated by code execution with tools." This happens even though we never
 *    declare code_execution ourselves.
 *  - Search/fetch errors return HTTP 200 with `content` as a single error OBJECT
 *    rather than a LIST. Under dynamic filtering those error blocks may never
 *    surface at all (nested results come back encrypted), so run health must NOT
 *    depend on seeing them — hence the emit-never-called and zero-search gates.
 *
 * No secrets are logged. The API key is passed to the transport and never printed,
 * and no URL with query parameters is logged.
 */

import { matchesAnyDomain, rosterEntry, type RosterEntry } from './roster.js';
import type { EmitFindingsPayload, ResearchResult, RetrievedUrl, TokenUsage } from './types.js';
import { CHANGE_TYPES, CONFIDENCES, ORIGINATORS, SCOPES, UNREACHABLE_REASON_CODES } from './types.js';

export const MODEL = 'claude-opus-5';
export const MAX_TOKENS = 32_000;
export const TURN_BUDGET = 12;
export const WEB_SEARCH_TOOL = 'web_search_20260318';
export const WEB_FETCH_TOOL = 'web_fetch_20260318';
/** Bounds text content per fetch. Documented NOT to bound PDFs, so fetchUses is
 *  the real cost ceiling. */
export const MAX_FETCH_CONTENT_TOKENS = 30_000;

/** Injected so tests are hermetic — no live API in `npm test`. */
export interface MessagesTransport {
  (payload: unknown): Promise<{ status: number; body: string }>;
}

export interface ResearchOptions {
  payerKey: string;
  windowStart: string;
  windowEnd: string;
  /** Identity lines for findings already reported, so the model suppresses them.
   *  Empty on a first run. */
  priorState?: string[];
  focus: string;
  transport: MessagesTransport;
  now?: () => number;
}

const strField = (description: string) => ({ type: 'string', description });

